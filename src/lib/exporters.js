import * as THREE from 'three';
import { Capacitor, registerPlugin } from '@capacitor/core';

const AxisFiles = registerPlugin('AxisFiles');

/** Convert model bytes to aligned base64 chunks for the native save picker. */
async function encodeFileForAndroid(blob) {
  const bytes = new Uint8Array(await blob.arrayBuffer());
  const blockSize = 24576; // multiple of 3: intermediate base64 blocks concatenate safely
  const parts = [];
  for (let offset = 0; offset < bytes.length; offset += blockSize) {
    const block = bytes.subarray(offset, offset + blockSize);
    parts.push(btoa(String.fromCharCode(...block)));
  }
  return parts.join('');
}


export function exportOBJ(meshes) {
  let output = '# AXIS 3D OBJ Export\n\n';
  let vOffset = 0;

  for (const mesh of meshes) {
    const vertexIndex = new Map(mesh.vertices.map((v, i) => [v.id, vOffset + i + 1]));
    const matrix = new THREE.Matrix4().compose(mesh.position, new THREE.Quaternion().setFromEuler(mesh.rotation), mesh.scale);
    output += `o ${String(mesh.name || 'Object').replace(/[\r\n]/g, ' ')}\n`;
    for (const v of mesh.vertices) {
      const p = new THREE.Vector3(v.x, v.y, v.z).applyMatrix4(matrix);
      output += `v ${p.x.toFixed(6)} ${p.y.toFixed(6)} ${p.z.toFixed(6)}\n`;
    }
    for (const face of mesh.faces) {
      if (face.length < 3) continue;
      const indices = face.map((id) => vertexIndex.get(id));
      if (indices.some((index) => index === undefined)) throw new Error('Cannot export a face with a missing vertex.');
      output += `f ${indices.join(' ')}\n`;
    }
    output += '\n';
    vOffset += mesh.vertices.length;
  }
  return output;
}

export function exportFBX(meshes) {
  let fbx = '';
  fbx += '; FBX 7.3.0 project file\n';
  fbx += '; Generated by Forge3D\n\n';
  fbx += 'FBXHeaderExtension: {\n';
  fbx += '\tFBXHeaderVersion: 1003\n';
  fbx += '\tFBXVersion: 7300\n';
  fbx += '\tCreationTimeStamp: {\n';
  fbx += '\t\tVersion: 1000\n';
  fbx += '\t\tYear: 2026\n\t\tMonth: 7\n\t\tDay: 12\n';
  fbx += '\t\tHour: 0\n\t\tMinute: 0\n\t\tSecond: 0\n';
  fbx += '\t\tMillisecond: 0\n';
  fbx += '\t}\n';
  fbx += '\tCreator: "Forge3D"\n';
  fbx += '}\n\n';
  fbx += 'GlobalSettings: {\n\tVersion: 1000\n\tProperties70: {\n';
  fbx += '\t\tP: "UpAxis", "int", "Integer", "",1\n';
  fbx += '\t\tP: "UpAxisSign", "int", "Integer", "",1\n';
  fbx += '\t\tP: "FrontAxis", "int", "Integer", "",2\n';
  fbx += '\t\tP: "FrontAxisSign", "int", "Integer", "",1\n';
  fbx += '\t\tP: "CoordAxis", "int", "Integer", "",0\n';
  fbx += '\t\tP: "CoordAxisSign", "int", "Integer", "",1\n';
  fbx += '\t}\n}\n\n';
  fbx += 'Definitions: {\n\tVersion: 100\n\tCount: 3\n';
  fbx += '\tObjectType: "GlobalSettings" {\n\t\tCount: 1\n\t}\n';
  fbx += '\tObjectType: "Model" {\n\t\tCount: ' + meshes.length + '\n\t}\n';
  fbx += '\tObjectType: "Geometry" {\n\t\tCount: ' + meshes.length + '\n\t}\n';
  fbx += '}\n\n';

  fbx += 'Objects: {\n';

  let geomUid = 1000000;
  let modelUid = 1000001;

  for (const mesh of meshes) {
    const name = String(mesh.name || 'Object').replace(/["\r\n]/g, ' ');
    const vertexIndex = new Map(mesh.vertices.map((v, i) => [v.id, i]));
    const faces = mesh.faces.filter((face) => face.length >= 3);
    const polygonVertexCount = faces.reduce((sum, face) => sum + face.length, 0);
    const fparts = [];
    const nparts = [];
    for (const face of faces) {
      const indices = face.map((id) => vertexIndex.get(id));
      if (indices.some((index) => index === undefined)) throw new Error('Cannot export a face with a missing vertex.');
      indices[indices.length - 1] = ~indices[indices.length - 1];
      fparts.push(...indices);
      const a = mesh.getVertexVector(face[0]);
      const b = mesh.getVertexVector(face[1]);
      const c = mesh.getVertexVector(face[2]);
      const n = new THREE.Vector3().subVectors(b, a).cross(new THREE.Vector3().subVectors(c, a)).normalize();
      for (let k = 0; k < face.length; k++) nparts.push(n.x.toFixed(6), n.y.toFixed(6), n.z.toFixed(6));
    }

    fbx += `\tGeometry: ${geomUid}, "Geometry::${name}", "Mesh" {\n`;
    fbx += `\t\tVertices: *${mesh.vertices.length * 3} {\n\t\t\ta: `;
    fbx += mesh.vertices.map((v) => `${v.x.toFixed(6)},${v.y.toFixed(6)},${v.z.toFixed(6)}`).join(',') + '\n\t\t}\n';
    fbx += `\t\tPolygonVertexIndex: *${polygonVertexCount} {\n\t\t\ta: ${fparts.join(',')}\n\t\t}\n`;
    fbx += '\t\tGeometryVersion: 124\n';
    fbx += '\t\tLayerElementNormal: 0 {\n\t\t\tVersion: 101\n\t\t\tName: ""\n\t\t\tMappingInformationType: "ByPolygonVertex"\n\t\t\tReferenceInformationType: "Direct"\n';
    fbx += `\t\t\tNormals: *${polygonVertexCount * 3} {\n\t\t\t\ta: ${nparts.join(',')}\n\t\t\t}\n`;
    fbx += '\t\t}\n\t\tLayer: 0 {\n\t\t\tVersion: 100\n\t\t\tLayerElement: {\n\t\t\t\tType: "LayerElementNormal"\n\t\t\t\tTypedIndex: 0\n\t\t\t}\n\t\t}\n\t}\n';

    fbx += `\tModel: ${modelUid}, "Model::${name}", "Mesh" {\n`;
    fbx += '\t\tVersion: 232\n\t\tProperties70: {\n';
    fbx += `\t\t\tP: "Lcl Translation", "Lcl Translation", "", "A",${mesh.position.x.toFixed(6)},${mesh.position.y.toFixed(6)},${mesh.position.z.toFixed(6)}\n`;
    fbx += `\t\t\tP: "Lcl Rotation", "Lcl Rotation", "", "A",${(mesh.rotation.x * 180 / Math.PI).toFixed(6)},${(mesh.rotation.y * 180 / Math.PI).toFixed(6)},${(mesh.rotation.z * 180 / Math.PI).toFixed(6)}\n`;
    fbx += `\t\t\tP: "Lcl Scaling", "Lcl Scaling", "", "A",${mesh.scale.x.toFixed(6)},${mesh.scale.y.toFixed(6)},${mesh.scale.z.toFixed(6)}\n`;
    fbx += '\t\t}\n\t}\n';

    geomUid += 2;
    modelUid += 2;
  }

  fbx += '}\n\n';

  fbx += 'Connections: {\n';
  geomUid = 1000000;
  modelUid = 1000001;
  for (let i = 0; i < meshes.length; i++) {
    fbx += `\tC: "OO",${geomUid},${modelUid}\n`;
    fbx += `\tC: "OO",${modelUid},0\n`;
    geomUid += 2;
    modelUid += 2;
  }
  fbx += '}\n';

  return fbx;
}

export async function downloadFile(content, filename, mimeType = 'text/plain') {
  const blob = new Blob([content], { type: mimeType });
  if (!blob.size) throw new Error('Export produced an empty file.');
  // Real Android save picker, backed by a native Storage Access Framework
  // document. This does not need Base44, Downloads permissions, or a share app.
  if (Capacitor.isNativePlatform() && Capacitor.getPlatform() === 'android') {
    const data = await encodeFileForAndroid(blob);
    try {
      const result = await AxisFiles.saveFile({ filename, mimeType, data });
      if (!result?.saved) throw new Error('Android did not confirm the file was saved.');
      return 'saved';
    } catch (error) {
      if (error?.code === 'CANCELED') throw new Error('File saving was canceled.');
      throw new Error(error?.message || 'Android could not save the file.');
    }
  }
  // Android WebViews often do not handle blob: anchor downloads. Use the
  // operating system's file sharing/saving sheet when file sharing is supported.
  const isAndroid = /Android/i.test(navigator.userAgent);
  if (isAndroid && typeof navigator.share === 'function' && typeof navigator.canShare === 'function') {
    const file = new File([blob], filename, { type: mimeType });
    if (navigator.canShare({ files: [file] })) {
      try {
        await navigator.share({ files: [file], title: filename });
        return 'shared';
      } catch (error) {
        if (error?.name === 'AbortError') throw new Error('File saving was canceled.');
        // A failed share must not silently report success; try browser download.
      }
    }
  }
  // No server upload fallback: Android uses the local share sheet when
  // available, otherwise we request a browser download from a local blob.
  const url = URL.createObjectURL(blob);
  try {
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    a.remove();
  } finally {
    setTimeout(() => URL.revokeObjectURL(url), 60000);
  }
  return 'requested';
}